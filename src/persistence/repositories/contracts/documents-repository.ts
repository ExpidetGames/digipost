export { DOCUMENT_KINDS } from "@/modules/intake";
export type { DocumentKind } from "@/modules/intake";

export type DocumentRow = InferSelectModel<typeof documents>;

export type CreateDocumentRow = {
  /** Pre-generated by the use case (not the database's `defaultRandom()`): the storage key
   * is built from this id and the object is written to storage *before* the row exists
   * (decisions/0015-documents-and-quotas.md's upload path), so the id must be known first. */
  id: string;
  workspaceId: string;
  uploadedByUserId: string | null;
  originalFileName: string;
  mimeType: string;
  pageCount: number;
  sizeBytes: number;
  storageKey: string;
  /** F1b: sha256 of the uploaded bytes (`@/modules/intake`'s `fileHash`) - always set for a
   * new upload; `findByFileHash`'s own duplicate check runs before this insert. */
  fileHash: string;
};

/** A document row joined with the display fields the inbox list and detail view need -
 * currently just who uploaded it - without a second round trip per row. */
export type DocumentWithRelations = DocumentRow & {
  uploadedByEmail: string | null;
};

/** The processing pipeline's own output (decisions/0016-processing-pipeline-and-ai.md,
 * decisions/0021-extraction-direction-and-invoice-fields.md), written in one update once OCR +
 * analysis + the searchable PDF all succeeded. `direction` is always one of
 * `DOCUMENT_DIRECTIONS` here (never `null`) - by the time `markDone` runs, C2's direction
 * decision has always run, even when it could only conclude `unknown`. Every invoice-shaped
 * field is `null` for a non-invoice document, or when the analyzer found nothing invoice-shaped
 * - parsed from the model's raw text in code (`@/modules/documents`'s amount/date parsing),
 * never trusted as already-structured. */
export type MarkDocumentDoneInput = {
  ocrText: string;
  ocrBlocks: unknown;
  title: string | null;
  sender: string | null;
  documentDate: string | null;
  summary: string | null;
  searchablePdfKey: string;
  direction: DocumentDirection;
  invoiceNumber: string | null;
  totalAmountCents: number | null;
  currency: string | null;
  dueDate: string | null;
  paymentIban: string | null;
  paymentReference: string | null;
  paidNote: string | null;
  /** F1b (decisions/0020-universal-intake.md, decisions/0022-intake-wiring.md): the OCR'd
   * document's recognized kind - via `IntakeClassifier` on the OCR text, or self-identified
   * from an embedded ZUGFeRD/Factur-X/XRechnung invoice XML when one is present (which then
   * also takes priority over the model for the invoice fields above). `intakeStatus` stays at
   * its schema default (`not_applicable`) for every document that goes through this OCR path
   * - the confirmation flow only ever gates a tabular financial import. */
  kind: DocumentKind;
  /** F3b (decisions/0025-payment-matching-wiring.md): `open` when `direction` is
   * `incoming`/`outgoing` and a `totalAmountCents` was extracted, `not_applicable` otherwise -
   * computed by the use case (`PAYMENT_STATUSES`, `@/modules/payments`), never by this
   * repository (WEBAPP_TEMPLATE_SPEC.md §5.3: no business logic here). */
  paymentStatus: PaymentStatus;
};

/** F1b: the non-OCR intake path's own terminal write (camt.053, a known-fingerprint tabular
 * source, or an unrecognized tabular source's proposal) - sets `status: "done"` without
 * touching any OCR-specific column (they stay `null`, this document was never OCR'd). */
export type MarkIntakeResultInput = {
  kind: DocumentKind;
  /** F4 (decisions/0026-platform-settlements.md): only meaningful alongside `kind`
   * `payout_report`/`platform_settlement` - `null` for every other kind (a camt.053 bank
   * statement, or the OCR path, never sets this). */
  platform: SettlementPlatform | null;
  intakeStatus: DocumentIntakeStatus;
  /** The validated classification and, for a tabular source, the normalized rows/settlement
   * lines (or a compact summary when too large) - see `decisions/0022-intake-wiring.md` for
   * the exact per-`intakeStatus` shape. */
  intakeResult: unknown;
};

export type ListDocumentsFilter = {
  /** `websearch_to_tsquery('german', q)` against `documents.search_vector`; result order
   * switches to `ts_rank` descending when set (architecture brief). */
  q?: string;
  status?: DocumentStatus;
  /** decisions/0021-extraction-direction-and-invoice-fields.md's inbox filter
   * ("Eingang"/"Ausgang"/"Alle" - `undefined` here is "Alle", no filter). */
  direction?: DocumentDirection;
  /** decisions/0022-intake-wiring.md's inbox kind filter (`undefined` is "Alle"). */
  kind?: DocumentKind;
  /** F3b (decisions/0025-payment-matching-wiring.md): the inbox's "offen/überfällig/bezahlt"
   * filter. Matched against the EFFECTIVE status (`@/modules/payments`'s
   * `resolveDisplayStatus` applied in SQL: a stored `open`/`partially_paid` row past its due
   * date counts as `overdue` for this filter too), not the raw stored column - see
   * `documents-repository.ts`'s `list` implementation for the exact `CASE` expression. Only
   * `open`/`overdue`/`paid` are offered by the UI (`partially_paid`/`settled`/
   * `no_document_needed`/`not_applicable` have no dedicated filter option in this phase).
   */
  paymentStatus?: "open" | "overdue" | "paid";
  /** decisions/0058-inbox-sorts-by-the-document-s-own-date.md. `documentDate` orders by
   * `coalesce(document_date, created_at)` so a document with no own date (every tabular
   * import) keeps its place in the timeline instead of sinking to the end; `uploaded` orders
   * by `created_at` alone. Either way `created_at desc, id desc` follows as the deterministic
   * tie-break offset pagination needs. A search (`q`) still ranks first, then this. Spelled
   * out here rather than imported from `@/modules/documents`' `DocumentSort`, exactly like
   * `paymentStatus` above: a contract does not depend on a module that depends on it. */
  sort?: "documentDate" | "uploaded";
  /** The "Start" work-list page's own inbox link (its "Wartet auf Bestätigung" bucket): only
   * `pending_confirmation` is ever offered as a filter value - the same narrowing
   * `paymentStatus` above already applies for its own filter values. */
  intakeStatus?: "pending_confirmation";
  /** decisions/0066-abschluss-check-and-export.md: the inbox's own date-range filter, and
   * what the Abschluss's check links carry so a period-scoped count opens a period-scoped
   * list. Both bounds are inclusive ISO `YYYY-MM-DD` dates, either may be absent, and both
   * are matched against the EFFECTIVE date (the shared `documentEffectiveDate` expression
   * `sort: "documentDate"` already orders by and the Abschluss already scopes its period by),
   * never against `created_at` or `document_date` alone - a second notion of "a document's
   * date" is exactly what that ADR exists to prevent. */
  from?: string;
  to?: string;
  /** 1-based. */
  page: number;
  pageSize: number;
};

/** A `list` row: `findById`'s shape plus the counterparty the inbox names a document after
 * (decisions/0059-generated-document-names.md). Only `list` resolves it, so it is a type of
 * its own rather than a field on `DocumentWithRelations` that every other read would have to
 * leave `null`. */
export type DocumentListRow = DocumentWithRelations & {
  /** The contact linked in the role this document's direction makes the counterparty: the
   * `sender` of an incoming document, the `recipient` of an outgoing one. `null` when nothing
   * is linked, which is every tabular import. */
  counterpartyName: string | null;
  /** decisions/0060-app-store-reports-are-named-by-their-period.md: the `YYYY-MM` an Apple or
   * Google report covers, read out of `intakeResult.appStorePayout.period`. `null` for every
   * other document, including a bank statement. */
  reportPeriod: string | null;
  /** decisions/0061-a-statement-is-dated-by-its-last-booking.md: the latest booking date in a
   * bank statement, read out of `intakeResult.lastBookingDate`. `null` for every other
   * document, and for a statement imported before that field existed. */
  statementLastBooking: string | null;
};

/** The Abschluss's five-item check, document half (decisions/0066-abschluss-check-and-export.md).
 * Every field is a real SQL `count(*)`, all four computed in one round trip over the same
 * period-scoped row set. */
export type ClosingDocumentCounts = {
  /** Every document in the period, whatever its status - the "an empty check is not an empty
   * period" guard the ADR insists on. */
  total: number;
  /** "Belege ohne Zahlung": EFFECTIVE payment status `open` or `overdue` (the same SQL `CASE`
   * `list`'s own `paymentStatus` filter uses, so a stored `open` past its due date counts). */
  openOrOverduePayments: number;
  /** "Wartet auf Bestätigung". */
  pendingIntakeConfirmation: number;
  /** "Verarbeitung fehlgeschlagen". */
  failedProcessing: number;
};

/** One confirmed (document -> transaction) link, as the export's cross references need it:
 * not a count but the counterpart itself (decisions/0066-abschluss-check-and-export.md). The
 * booking date and amount travel along because the counterpart may lie OUTSIDE the exported
 * period (a January booking settling a December invoice) and so has no row, and no "Nr.", in
 * this workbook - the export then names it by date and amount instead of dropping it. */
export type ClosingLinkedTransaction = {
  id: string;
  /** ISO `YYYY-MM-DD`. */
  bookingDate: string;
  /** Signed, in cents: the transaction's own full amount, not the allocated portion. */
  amountCents: number;
  /** The transaction's own currency, falling back to its account's. */
  currency: string;
  /** The positive portion of this transaction the document claims
   * (`document_transactions.allocated_amount_cents`). */
  allocatedAmountCents: number;
};

/** One row of the export's "Dokumente" sheet, and the source of one `belege/`/
 * `ausgangsrechnungen/` entry (decisions/0066-abschluss-check-and-export.md). Deliberately NOT
 * `DocumentRow`: the export needs the derived effective date, the resolved counterparty, the
 * effective payment status, and the confirmed links, and needs none of the OCR text or
 * blocks. */
export type ClosingDocumentRow = {
  id: string;
  /** ISO `YYYY-MM-DD` - the shared effective date (decisions/0058/0060/0061). */
  effectiveDate: string;
  originalFileName: string;
  mimeType: string;
  /** `null` when processing never produced one; the export then keeps the original upload. */
  searchablePdfKey: string | null;
  kind: DocumentKind;
  platform: string | null;
  direction: DocumentDirection | null;
  documentDate: string | null;
  sender: string | null;
  counterpartyName: string | null;
  reportPeriod: string | null;
  statementLastBooking: string | null;
  invoiceNumber: string | null;
  totalAmountCents: number | null;
  currency: string | null;
  /** The EFFECTIVE status, same expression as everywhere else. */
  paymentStatus: string;
  /** Every transaction this document is settled by, oldest booking first. The export turns
   * these into the "Zugeordnete Buchungen" cross references and into the "Zuordnungen" sheet;
   * `.length` is the count the column used to hold. */
  confirmedTransactions: ClosingLinkedTransaction[];
};

export type ListDocumentsResult = {
  items: DocumentListRow[];
  /** Whether a page after this one has at least one more matching row - offset pagination
   * without a separate `count(*)` query. */
  hasMore: boolean;
};

export interface DocumentRepository {
  create(input: CreateDocumentRow): Promise<DocumentRow>;
  /** Documents currently stored in the workspace, any status (architecture brief's product
   * decision 1: the total limit counts current stock, deleting frees capacity). */
  countByWorkspace(workspaceId: string): Promise<number>;
  /** The "Start" work-list page's "Wartet auf Bestätigung" bucket - a real `count(*)`, not a
   * `list` call measured by `.length` (P6 review finding A7 applies here just as much as it
   * did to `countByWorkspace`). */
  countPendingIntakeConfirmation(workspaceId: string): Promise<number>;
  /** The "Start" work-list page's "Verarbeitung fehlgeschlagen" bucket. */
  countFailed(workspaceId: string): Promise<number>;
  /** The "Start" work-list page's "Überfällig" bucket - the EFFECTIVE payment status (the
   * same SQL `CASE` expression `list`'s own `paymentStatus` filter uses, not the raw stored
   * column), so a stored `open`/`partially_paid` row past its due date is counted too. */
  countOverduePayments(workspaceId: string): Promise<number>;
  /** F1b's exact-duplicate check: `null` when no document in `workspaceId` currently has this
   * `fileHash` (a `null` `fileHash` column never matches - Postgres's own `= null` semantics
   * already guarantee this, but `createFromUpload` never calls this with an empty hash
   * either). */
  findByFileHash(workspaceId: string, fileHash: string): Promise<{ id: string; originalFileName: string } | null>;
  findById(workspaceId: string, id: string): Promise<DocumentWithRelations | null>;
  /** F1b's semantic-duplicate hint (decisions/0020-universal-intake.md,
   * decisions/0022-intake-wiring.md): every OTHER document in `workspaceId` sharing this exact
   * `invoiceNumber` (the existing `(workspace_id, invoice_number)` index), for
   * `@/modules/documents`'s `findSemanticDuplicate` to narrow further by sender/amount.
   * `excludeDocumentId` is filtered out here rather than by the caller. */
  findByInvoiceNumber(
    workspaceId: string,
    invoiceNumber: string,
    excludeDocumentId: string,
  ): Promise<{ id: string; originalFileName: string; sender: string | null; totalAmountCents: number | null }[]>;
  /** F3b: every OTHER document sharing this exact invoice number, with just enough to answer
   * "is the underlying invoice already paid" - `@/modules/payments`'s reminder-already-paid
   * callout ("Diese Rechnung wurde bereits am ... bezahlt"). A narrower sibling of
   * `findByInvoiceNumber` above (kept separate rather than widening that method's return
   * shape, which F1b's semantic-duplicate hint already depends on exactly as it is). */
  findPaymentStatusByInvoiceNumber(
    workspaceId: string,
    invoiceNumber: string,
    excludeDocumentId: string,
  ): Promise<{ id: string; paymentStatus: PaymentStatus; paidAt: Date | null }[]>;
  list(workspaceId: string, filter: ListDocumentsFilter): Promise<ListDocumentsResult>;
  /** Deletes the row; the returned row's `storageKey`/`searchablePdfKey` let the use case
   * delete the matching objects from `src/platform/object-storage` in the same operation
   * (decisions/0012-object-storage.md: deleting a document row does not by itself delete its
   * objects). `null` (not an error) if the document does not exist in this workspace. */
  deleteById(workspaceId: string, id: string): Promise<DocumentRow | null>;
  /** Status -> "processing", clears `errorCode` - the start of an attempt, whether the
   * first one (right after upload) or a retry after a previous failure. */
  markProcessing(workspaceId: string, id: string): Promise<void>;
  /** decisions/0072: records the kind a human chose and starts a processing attempt in one
   * write (status -> "processing", clears `errorCode`, sets `manualKind`). */
  markProcessingWithManualKind(workspaceId: string, id: string, manualKind: DocumentKind): Promise<void>;
  /** Status -> "done", fills every processing-derived field, sets `processedAt`. */
  markDone(workspaceId: string, id: string, input: MarkDocumentDoneInput): Promise<void>;
  /** Status -> "failed", records the stable error code (AGENTS.md "Code"). */
  markFailed(workspaceId: string, id: string, errorCode: string): Promise<void>;
  /** F1b's non-OCR intake path (camt.053, a known-fingerprint tabular source, or an
   * unrecognized tabular source's proposal) - status -> "done", sets `processedAt`, never
   * touches an OCR-specific column. */
  markIntakeResult(workspaceId: string, id: string, input: MarkIntakeResultInput): Promise<void>;
  /** The confirmation action ("Bestätigen und importieren"): applies the (possibly
   * user-edited) mapping's final, re-validated result and sets `intakeStatus: "confirmed"`. */
  confirmIntake(workspaceId: string, id: string, input: { kind: DocumentKind; platform: SettlementPlatform | null; intakeResult: unknown }): Promise<void>;
  /** "Ablehnen": sets `intakeStatus: "rejected"` - nothing is imported, `intakeResult` keeps
   * the rejected proposal for the record. */
  rejectIntake(workspaceId: string, id: string): Promise<void>;
  /** F3b: `PaymentsUseCases`'s own write, after every matching decision (confirm/reject/
   * link/unlink) and at the end of a matching run - this repository (the `documents` owner)
   * is still the only writer of `documents`, `PaymentsUseCases` calls this method directly
   * even though it belongs to another owner area (`documents-repository.ts`'s own header
   * comment: "only this repository writes, even though the caller orchestrating it belongs
   * to another owner area"). */
  updatePaymentStatus(workspaceId: string, id: string, input: { paymentStatus: PaymentStatus; paidAt: Date | null }): Promise<void>;
  /** F3b: every invoice-shaped document (`direction` `incoming`/`outgoing`, a
   * `totalAmountCents`) still needing payment attention (`paymentStatus` `open`,
   * `partially_paid`, or `overdue`) - the candidate-document pool `PaymentsUseCases.runMatching`
   * builds `MatchableDocument`s from, and "Offene Posten"'s own listing (the same query serves
   * both: a document worth matching against is, by definition, a document worth showing as an
   * open item).
   *
   * `range` (decisions/0066-abschluss-check-and-export.md) narrows "Offene Posten" to one
   * period, by the SAME `documentEffectiveDate` expression `list` and the Abschluss's own
   * counts use. It is only ever passed by that page: `runMatching`'s candidate pool calls
   * this with no range at all, because an invoice from any month may be the one a transaction
   * settles. */
  listInvoiceCandidates(workspaceId: string, range?: DateRange): Promise<DocumentRow[]>;
  /** F5 (decisions/0027-hardening-and-deletion.md): the retention cron's own read - every
   * document with `intake_status = 'rejected'` and `updated_at` before `cutoff`, across EVERY
   * workspace (deliberately unscoped - background maintenance, the same shape
   * `src/platform/jobs`'s cron sweep already uses for `claimDue` with no `workspaceId`
   * filter). `updated_at` is the rejection timestamp proxy: `rejectIntake` is the last write a
   * rejected document's row ever receives in the ordinary product flow, so there is no
   * separate `rejected_at` column to maintain. */
  listIntakeRejectedBefore(cutoff: Date): Promise<{ id: string; workspaceId: string }[]>;
  /** decisions/0048-app-store-reports.md: every confirmed Apple `payout_report`/Google
   * `platform_settlement` document for one platform - `PaymentsUseCases`'s app-store
   * payout-to-bank-credit pairing reads each one's own `intakeResult.appStorePayout` (period,
   * payout/net total) to decide which bank credit explains it. Small by construction (one row
   * per month a workspace has ever uploaded a report for), so this returns everything at once
   * rather than paginating like `list` does for the inbox. */
  listConfirmedSettlementReports(workspaceId: string, platform: Extract<SettlementPlatform, "apple" | "google">): Promise<{ id: string; intakeResult: unknown }[]>;
  /** Abschluss (decisions/0066-abschluss-check-and-export.md): the four document counts for one
   * period, scoped by `documentEffectiveDate` - the SAME SQL expression `list` orders the inbox
   * by, exported from `repositories/drizzle/documents-repository.ts` precisely so the Abschluss
   * and the inbox can never disagree about which month a document belongs to. `from`/`to` are
   * inclusive ISO `YYYY-MM-DD` dates. */
  countsForPeriod(workspaceId: string, from: string, to: string): Promise<ClosingDocumentCounts>;
  /** Abschluss: every document in the period, oldest first, in the shape the export's
   * "Dokumente" sheet and its `belege/` entries need. Not paginated - a period's worth of
   * documents is bounded by what one small business receives in a year (see
   * `src/modules/closing/README.md`'s own note on the practical size limit). */
  listForPeriod(workspaceId: string, from: string, to: string): Promise<ClosingDocumentRow[]>;
}
